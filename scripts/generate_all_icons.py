"""
generate_all_icons.py
Creates pixel-art 16x16 icons for all tools, biomes, actions, and stats in Planet Painters,
eliminating all Unicode emojis and replacing them with authentic pixel art.
"""
import os
from PIL import Image

OUT = r"resources/ui/icons"
os.makedirs(OUT, exist_ok=True)

def parse(art, pal):
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    lines = [l.strip() for l in art.strip().split("\n") if l.strip()]
    for y, line in enumerate(lines[:16]):
        for x, ch in enumerate(line[:16]):
            if ch in pal and pal[ch] is not None:
                im.putpixel((x, y), pal[ch])
    return im

